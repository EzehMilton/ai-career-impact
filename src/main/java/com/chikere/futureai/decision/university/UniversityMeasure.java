package com.chikere.futureai.decision.university;

/**
 * The authoritative university measures.
 *
 * <p>These are NOT the professional measures. {@code FUTURE_READINESS} is not AI Exposure inverted,
 * and a university value must never be compared numerically with a professional value.</p>
 */
public enum UniversityMeasure {
    FUTURE_READINESS,
    AI_COMPLEMENTARITY,
    HUMAN_DIFFERENTIATION,
    SKILL_TRANSFERABILITY,
    CAREER_ADAPTABILITY
}
